/** Detect the most likely language of a text sample. */
export function detectLanguage(text: string): LanguageCode {
  const sample = text.slice(0, 2000); // Only need a sample
  const len = sample.length;
  if (len === 0) return "en";

  // Script-based detection (non-Latin scripts)
  const cjkCount = (sample.match(CJK_RE) ?? []).length;
  const hiraganaCount = (sample.match(HIRAGANA_RE) ?? []).length;
  const katakanaCount = (sample.match(KATAKANA_RE) ?? []).length;
  const hangulCount = (sample.match(HANGUL_RE) ?? []).length;
  const cyrillicCount = (sample.match(CYRILLIC_RE) ?? []).length;
  const arabicCount = (sample.match(ARABIC_RE) ?? []).length;

  const threshold = len * 0.15;

  if (hiraganaCount + katakanaCount > threshold) return "ja";
  if (hangulCount > threshold) return "ko";
  if (cjkCount > threshold) return "zh";
  if (cyrillicCount > threshold) return "ru";
  if (arabicCount > threshold) return "ar";

  // Latin script — use word frequency markers
  const words = sample.toLowerCase().split(/\s+/);
  const wordSet = new Set(words);
  let bestLang: LanguageCode = "en";
  let bestScore = 0;

  for (const [lang, markers] of LANG_MARKERS) {
    let score = 0;
    for (const m of markers) {
      if (wordSet.has(m)) score++;
    }
    if (score > bestScore) {
      bestScore = score;
      bestLang = lang;
    }
  }

  // Need at least 3 marker hits to override English default
  return bestScore >= 3 ? bestLang : "en";
}
